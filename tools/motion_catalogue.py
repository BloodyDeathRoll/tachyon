"""Refresh engines/remotion/motion.yaml from prompt-motion.com: one style per entry with a usable prompt.

The weekly plan gives every reel a different style from it (spine/week.py) so the films stop
looking alike. Videos and prompts belong to their creators: the films adapt a technique, never copy a piece.

    python3 tools/motion_catalogue.py           # scrape and name new styles
    python3 tools/motion_catalogue.py --label   # only name the styles that have no name yet
"""

from __future__ import annotations

import html
import json
import re
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

import yaml

SITE = "https://prompt-motion.com"
OUT = Path(__file__).resolve().parent.parent / "engines" / "remotion" / "motion.yaml"
MIN_PROMPT = 120   # shorter ones are "make a similar version" replies, not a technique
SKIP_TAGS = {"Characters", "Photos", "Music"}   # needs art or audio we do not have


def get(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "tachyon-motion-catalogue"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode()


def text(s: str) -> str:
    return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()


def entry(slug: str, page: str) -> dict | None:
    m = re.search(r'id="entry-prompt"[^>]*>(.*?)</div>', page, re.S)
    title = re.search(r"<h1[^>]*>(.*?)</h1>", page, re.S)
    if not m or not title:
        return None
    prompt = text(m.group(1))
    tags = [text(t) for t in re.findall(r'href="/tags/[^"]+">(.*?)</a>', page)]
    if len(prompt) < MIN_PROMPT or set(tags) & SKIP_TAGS:
        return None
    return {"id": slug, "title": text(title.group(1)), "tags": tags, "url": f"{SITE}/{slug}", "prompt": prompt}


def label(styles: list[dict]) -> None:
    """Give each style without one a short `style` name (the dashboard pill, and what notes can ask for).
    Labels already in the file are kept, so a name the operator learned never changes."""
    todo = [{k: s[k] for k in ("id", "title", "tags", "prompt")} for s in styles if not s.get("style")]
    if not todo:
        return
    r = subprocess.run(["claude", "-p", "Name the animation style of each motion video below in 2-3 words, how it moves "
                        "and looks, not its subject (e.g. \"Particle swarm\", \"Kinetic typography\", \"Isometric UI build\"). "
                        "Answer with one JSON object {id: name} and nothing else.\n\n" + json.dumps(todo, ensure_ascii=False)],
                       capture_output=True, text=True, timeout=600)
    names = json.loads(r.stdout[r.stdout.find("{"):r.stdout.rfind("}") + 1])
    for s in styles:
        s["style"] = s.get("style") or names.get(s["id"])


def main() -> int:
    old = {s["id"]: s.get("style") for s in (yaml.safe_load(OUT.read_text()) or {}).get("styles", [])} if OUT.exists() else {}
    if "--label" in sys.argv:
        out = yaml.safe_load(OUT.read_text())["styles"]
        label(out)
        OUT.write_text(OUT.read_text().split("\n", 1)[0] + "\n" + yaml.safe_dump({"styles": out}, sort_keys=False, allow_unicode=True, width=110))
        print(sum(bool(s.get("style")) for s in out), "named")
        return 0
    slugs = sorted(set(re.findall(r'href="/([a-z0-9-]+-[0-9a-f]{6})"', get(SITE + "/"))))
    out = []
    for s in slugs:
        try:
            e = entry(s, get(f"{SITE}/{s}"))
        except Exception as ex:   # one broken entry never loses the rest
            print(f"skip {s}: {ex}", file=sys.stderr)
            continue
        if e:
            out.append({"id": e["id"], "style": old.get(s), **{k: v for k, v in e.items() if k != "id"}})
        time.sleep(0.3)
    label(out)
    OUT.write_text("# generated by tools/motion_catalogue.py; videos and prompts belong to their creators (url)\n"
                   + yaml.safe_dump({"styles": out}, sort_keys=False, allow_unicode=True, width=110))
    print(f"{len(out)} of {len(slugs)} entries -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
