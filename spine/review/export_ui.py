"""The local dashboard's look for the Worker's pages: app.py's CSS and page scripts as a TS
module, and its font and logo as static files (deploy/worker/public). One look, two servers.

    python -m spine.review.export_ui      # writes deploy/worker/src/pages/ui.gen.ts and public/static/*

tests/test_export_ui.py fails when the written files no longer match app.py."""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

from . import app as A

ROOT = Path(__file__).resolve().parents[2]
WORKER = ROOT / "deploy" / "worker"
GEN = WORKER / "src" / "pages" / "ui.gen.ts"
STATIC = WORKER / "public" / "static"
NAMES = ("CSS", "PV_JS", "SEG_JS", "LOCK_JS", "DTP_JS", "AUDIO_JS", "GEN_BTN", "EMPTY_HINT")
FILES = {"inter.woff2": A.FONT, "logo.svg": A.LOGO, "icon.svg": A.ICON}


def icons() -> dict[str, str]:
    """The paths inside app.py's icon(), read from its source (a dict literal local to the function)."""
    import ast
    import inspect
    fn = ast.parse(inspect.getsource(A.icon)).body[0]
    d = next(n.value for n in ast.walk(fn) if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "paths")
    return ast.literal_eval(d)


def module() -> str:
    head = "// Generated by `python -m spine.review.export_ui` from spine/review/app.py. Do not edit.\n"
    from .. import week as WK
    styles = {k: {"style": m.get("style"), "title": m.get("title"), "url": m.get("url")} for k, m in WK.motion_styles().items()}
    return (head + "".join(f"export const {n} = {json.dumps(getattr(A, n))};\n" for n in NAMES)
            + f"export const ENGINES: Record<string, string> = {json.dumps(WK.ENGINES)};\n"
            + f"export const ICONS: Record<string, string> = {json.dumps(icons())};\n"
            + f"export const MOTION_STYLES: Record<string, {{ style?: string; title?: string; url?: string }}> = {json.dumps(styles)};\n")


def write() -> list[str]:
    GEN.write_text(module())
    STATIC.mkdir(parents=True, exist_ok=True)
    for name, src in FILES.items():
        shutil.copyfile(src, STATIC / name)
    return [str(GEN.relative_to(ROOT)), *(str((STATIC / n).relative_to(ROOT)) for n in FILES)]


if __name__ == "__main__":
    print("\n".join(write()))
    sys.exit(0)
